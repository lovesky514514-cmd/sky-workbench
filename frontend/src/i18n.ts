export function initialLocale(): Locale {
  const saved = localStorage.getItem(localeStorageKey)
  if (saved === 'zh-CN' || saved === 'en-US') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export function translate(locale: Locale, source: string): string { return locale === 'zh-CN' ? (zhCN[source] ?? source) : source }
export function currentLocale(): Locale { return document.documentElement.lang === 'zh-CN' ? 'zh-CN' : 'en-US' }
